#!/usr/bin/env python3
"""Regenerates attestation-vectors.tsv: known answers for the canonicalizer's attestation message (decision D-014 v1.1).

The layout below is written from the decision text alone, with hashlib and struct, so the vectors are independent of
both the Rust program (programs/prequel/src/attestation.rs) and the TypeScript signer (packages/shared/src/attestation.ts).
Both test suites read the file this script writes.

    python3 -I packages/shared/canon/gen-attestation-vectors.py

Columns (tab separated): name, program id, config, event, outcome, canon hash, proposal name, display ticker, uri,
image hash, proposer, expiry, content hash, message (251 bytes), digest. Keys and hashes are hex.
"""
import hashlib
import pathlib
import struct

DOMAIN = b"PREQUEL-PROPOSE-V1"


def sha(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def label(text: str) -> bytes:
    """A deterministic 32-byte stand-in for a public key or hash."""
    return sha(text.encode())


def u16(n: int) -> bytes:
    return struct.pack("<H", n)


def content_hash(name: str, ticker: str, uri: str) -> bytes:
    n, t, u = name.encode(), ticker.encode(), uri.encode()
    return sha(u16(len(n)) + n + u16(len(t)) + t + u16(len(u)) + u)


def message(program, config, event, outcome, canon_hash, content, image, proposer, expiry) -> bytes:
    m = DOMAIN + program + config + event + bytes([outcome]) + canon_hash + content + image + proposer + struct.pack("<q", expiry)
    assert len(m) == 18 + 32 * 3 + 1 + 32 * 4 + 8 == 251
    return m


# (name, program, config, event, outcome, canonical ticker to hash, proposal name, DISPLAY ticker, uri, image, proposer, expiry)
long_name = "Café " * 5 + "Co"  # 5 x ("Cafe" with an accent + space) = 30 bytes, plus "Co": exactly 32 bytes
assert len(long_name.encode()) == 32
long_uri = "ipfs://" + "b" * 121
assert len(long_uri.encode()) == 128
cases = [
    ("basic", label("program-1"), label("config-1"), label("event-1"), 0, "VICT", "Victory Coin", "VICT", "ipfs://bafyvict", label("image-1"), label("proposer-1"), 1_800_000_600),
    # The display ticker is what is hashed (uppercased, digits kept), not the canonical form and not the raw input.
    ("lowercase input, digit kept in the display form", label("program-1"), label("config-1"), label("event-1"), 1, "BOB", "b0b Coin", "B0B", "ipfs://bafyb0b", label("image-2"), label("proposer-1"), 1_800_003_600),
    ("maximum lengths, multi-byte name, last outcome, largest expiry", label("program-1"), label("config-1"), label("event-2"), 7, "ABCDEFGHIJ", long_name, "ABCDEFGHIJ", long_uri, label("image-3"), label("proposer-2"), 2**63 - 1),
    ("other deployment, zero image hash, negative expiry", label("program-2"), label("config-2"), label("event-3"), 2, "ZZ", "Z", "ZZ", "https://example.org/z.json", bytes(32), label("proposer-3"), -1),
]

lines = ["# name<TAB>program<TAB>config<TAB>event<TAB>outcome<TAB>canon_hash<TAB>proposal_name<TAB>display_ticker<TAB>uri<TAB>image_hash<TAB>proposer<TAB>expiry<TAB>content_hash<TAB>message<TAB>digest. Generated by gen-attestation-vectors.py with hashlib, independent of the Rust and TypeScript code."]
for name, program, config, event, outcome, canon, pname, display, uri, image, proposer, expiry in cases:
    canon_hash = sha(canon.encode())
    content = content_hash(pname, display, uri)
    msg = message(program, config, event, outcome, canon_hash, content, image, proposer, expiry)
    lines.append("\t".join([
        name, program.hex(), config.hex(), event.hex(), str(outcome), canon_hash.hex(), pname, display, uri,
        image.hex(), proposer.hex(), str(expiry), content.hex(), msg.hex(), sha(msg).hex(),
    ]))
out = pathlib.Path(__file__).with_name("attestation-vectors.tsv")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out} ({len(cases)} vectors)")
