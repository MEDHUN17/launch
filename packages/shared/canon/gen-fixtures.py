#!/usr/bin/env python3
"""Regenerates fixtures.tsv. Expected canonical forms are written by hand below and hashed with hashlib, so the
fixtures are independent of both the Rust and the TypeScript implementations.

    python3 -I packages/shared/canon/gen-fixtures.py
"""
import hashlib
import pathlib

cases = [
    ("BOB", "BOB"), ("bob", "BOB"), ("B0B", "BOB"), ("b0b", "BOB"), ("BoB", "BOB"),
    ("PEPE", "PEPE"), ("pepe", "PEPE"), ("P3PE", "P3PE"),
    ("L1LI", "LILI"), ("S5S", "SSS"), ("50S", "SOS"), ("1234567890", "I234S6789O"),
    ("AB", "AB"), ("ABCDEFGHIJ", "ABCDEFGHIJ"), ("a1", "AI"), ("Z9", "Z9"), ("zz", "ZZ"), ("99", "99"),
    ("A", None), ("", None), ("ABCDEFGHIJK", None), ("AB CD", None), (" AB", None), ("AB ", None),
    ("AB-C", None), ("AB_C", None), ("A.B", None), ("$BOB", None),
    ("BÖB", None),            # letter with a diaeresis
    ("ßß", None),        # sharp s: JavaScript's toUpperCase() would turn it into "SS"
    ("ıı", None),        # dotless i: toUpperCase() would turn it into "I"
    ("ＢＯＢ", None),  # full-width letters
    ("İİ", None),        # dotted capital I
    ("\U0001f600\U0001f600", None),
    ("๑๒", None),        # Thai digits
]
lines = ["# input<TAB>canonical-or-ERR<TAB>sha256(canonical) hex. Generated by gen-fixtures.py with hashlib, independent of the Rust and TypeScript code."]
for inp, canon in cases:
    lines.append(f"{inp}\tERR\t" if canon is None else f"{inp}\t{canon}\t{hashlib.sha256(canon.encode()).hexdigest()}")
out = pathlib.Path(__file__).with_name("fixtures.tsv")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out} ({len(cases)} cases)")
